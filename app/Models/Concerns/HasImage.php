<?php

namespace App\Models\Concerns;

use App\Services\FileService\Models\File;
use App\Services\FileService\Models\FileObject;
use App\Services\FileService\Traits\HasFileObjects;
use App\Support\ExternalImage;
use Illuminate\Database\Eloquent\Relations\MorphOne;
use Illuminate\Support\Facades\Storage;
use Throwable;

/**
 * Model image stored through FileService as optimized presets (see App\FileConfigs).
 *
 * Sources, in priority order:
 *  1. imageObject — FileObject with presets (thumb/sm/md/lg/original);
 *  2. image       — a file just uploaded / generated to the public disk; converted to presets on save;
 *  3. image_url   — external URL (seed data until `php artisan images:localize`).
 */
trait HasImage
{
    use HasFileObjects;

    /** Presets used for srcset, smallest first. */
    protected static array $srcsetPresets = ['sm', 'md', 'lg'];

    /** Name of the file config (App\FileConfigs) holding this model's presets. */
    abstract public static function imageFileConfig(): string;

    public static function bootHasImage(): void
    {
        static::saved(function (self $model) {
            if ($model->image && ($model->wasRecentlyCreated || $model->wasChanged('image'))) {
                $model->convertUploadedImage();
            }
        });

        static::deleting(fn (self $model) => $model->unlinkFileObjects($model->fileObjects()->pluck('uuid')->all()));
    }

    public function imageObject(): MorphOne
    {
        return $this->morphOne(FileObject::class, 'fileable')
            ->where('type', static::imageFileConfig())
            ->orderByDesc('id');
    }

    /**
     * Replace the model image with a local file; all presets are generated by FileService.
     */
    public function attachImage(string $absolutePath, string $fileName): FileObject
    {
        $fileObject = resolve('file_service')->uploadSingle($absolutePath, $fileName, static::imageFileConfig());

        $this->attachFileObject($fileObject);   // also deletes the previous image and its files
        $this->unsetRelation('imageObject');

        return $fileObject;
    }

    /**
     * A fresh AI dish whose photo is still queued (GenerateDishImage), as opposed to a dish with no photo at all.
     */
    public function imagePending(): bool
    {
        return ($this->source ?? null) === 'ai'
            && ! $this->image && ! $this->imageObject
            && $this->created_at?->gt(now()->subMinutes(30))
            && resolve(\App\Services\Ai\NutritionAi::class)->imagesEnabled();
    }

    public function imageUrl(string $preset = 'md'): ?string
    {
        if ($file = $this->imageFile($preset)) {
            return $file->urlPublic();
        }

        if ($this->image) {
            return Storage::disk('public')->url($this->image);
        }

        return $this->image_url ? ExternalImage::resized($this->image_url, 1280) : null;
    }

    /**
     * "url 480w, url 960w, ..." for <img srcset>, or null when only a single source exists.
     */
    public function imageSrcset(): ?string
    {
        $object = $this->imageObject;

        if (! $object) {
            return $this->image || ! $this->image_url ? null : ExternalImage::srcset($this->image_url);
        }

        return $object->files
            ->whereIn('key', static::$srcsetPresets)
            ->filter(fn (File $file) => $file->path && $file->width)
            ->sortBy('width')
            ->map(fn (File $file) => $file->urlPublic().' '.$file->width.'w')
            ->implode(', ') ?: null;
    }

    /**
     * @return array{0: int|null, 1: int|null} intrinsic width/height of a preset (for width/height attributes)
     */
    public function imageDimensions(string $preset = 'md'): array
    {
        $file = $this->imageFile($preset);

        return [$file?->width, $file?->height];
    }

    private function imageFile(string $preset): ?File
    {
        $object = $this->imageObject;

        return $object?->findFile($preset) ?? $object?->findFile('sm') ?? $object?->findFile('original');
    }

    /**
     * Turn the raw upload in `image` into presets, then drop the raw file.
     * On failure the raw upload stays in place, so the page still has an image.
     */
    private function convertUploadedImage(): void
    {
        $disk = Storage::disk('public');

        if (! $disk->exists($this->image)) {
            return;
        }

        try {
            $this->attachImage($disk->path($this->image), basename($this->image));
        } catch (Throwable $e) {
            report($e);

            return;
        }

        $disk->delete($this->image);

        // We are inside `saved`: original attributes are not synced yet, so save() would see no change.
        $this->newQueryWithoutScopes()->whereKey($this->getKey())->update(['image' => null]);
        $this->setAttribute('image', null)->syncOriginalAttribute('image');
    }
}
